"""Generate WIT2 and native port dispatch from the schema-generated Rust model.

Rust is an intermediate, generated from the same schemas in this invocation; no
hand-maintained field lists. Only the reachable invoke/host/stream shapes enter
the component ABI. Business inputs remain in the single payloadJson envelope.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
from generate_contracts import Generator, ROOT, BASE


def kebab(name):
    return re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", name).replace("_", "-").lower()


def identifier(name):
    return "%" + name if name in {"type", "record", "variant", "enum", "flags", "resource", "func", "interface", "world", "use", "import", "export", "static", "constructor", "include", "with", "result", "option", "list", "tuple", "string", "bool"} else name


class Wit:
    def __init__(self):
        self.g = Generator()
        self.g.render()
        self.done, self.types = set(), []

    def reference(self, value):
        return self.g.refs[value["$ref"]]

    def convert(self, rust):
        rust = rust.strip()
        for container, wit in [("Vec", "list"), ("Option", "option")]:
            if rust.startswith(container + "<") and rust.endswith(">"):
                return wit + "<" + self.convert(rust[len(container)+1:-1]) + ">"
        if rust == "String": return "string"
        if rust == "()": return "tuple<>"
        if rust in ["u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64", "f32", "f64", "bool"]:
            return rust.replace("i", "s", 1) if rust.startswith("i") else rust
        if rust in ("Value", "BTreeMap<String, Value>"):
            raise ValueError("untyped JSON cannot silently enter a typed host ABI: " + rust)
        self.emit(rust)
        return kebab(rust)

    def emit(self, name):
        if name in self.done: return
        self.done.add(name)
        source = self.g.rs[name]
        wit = kebab(name)
        if "pub struct " + name + ";" in source:
            text = "type " + wit + " = u64;"
        elif "pub struct " + name + " {" in source:
            fields = re.findall(r"pub r#([a-z0-9_]+): (.+),", source)
            text = "record " + wit + " {\n" + "\n".join("    " + identifier(kebab(key)) + ": " + self.convert(kind) + "," for key, kind in fields) + "\n}"
        elif "pub enum " + name + " {" in source:
            variants = re.findall(r"    V([0-9]+)(?:\(([^\n]+)\))?,", source)
            kind = "variant" if any(typ for _, typ in variants) else "enum"
            text = kind + " " + wit + " {\n" + "\n".join("    v" + index + ("(" + self.convert(typ) + ")" if typ and typ != "()" else "") + "," for index, typ in variants) + "\n}"
        else:
            alias = re.fullmatch(r"pub type " + name + r" = (.+);\s*", source)
            if not alias: raise ValueError("unrecognized generated type: " + name)
            text = "type " + wit + " = " + self.convert(alias.group(1)) + ";"
        self.types.append(text)

    def render(self):
        ports = json.loads((ROOT / "schemas/host-ports.schema.json").read_text(encoding="utf-8"))
        methods = ports["x-wit-functions"]
        error = self.g.refs[ports["$id"] + "#/$defs/hostError"]
        self.emit("Invocation"); self.emit("Response"); self.emit(error)
        interfaces = {}
        native = []
        for method in methods:
            args = self.reference(method["arguments"])
            result = self.reference(method["returns"])
            no_result = " = ();" in self.g.rs[result]
            self.emit(args)
            if not no_result: self.emit(result)
            interfaces.setdefault(method["interface"], []).append((method["name"], args, None if no_result else result))
            native.append((method["interface"] + "." + method["name"], args, result))
        source_hash = hashlib.sha256((ROOT / "schemas/host-ports.schema.json").read_bytes()).hexdigest()
        header = "// Generated by tools/generate_wit.py; host schema SHA-256: " + source_hash + "\n"
        wit = header + "package bgxiong:vendor-adapter@2.0.0;\n\ninterface types {\n" + "\n\n".join("\n".join("  " + line for line in t.splitlines()) for t in self.types) + "\n}\n\n"
        for interface, functions in interfaces.items():
            names = sorted({error} | {args for _, args, _ in functions} | {result for _, _, result in functions if result})
            wit += "interface " + interface + " {\n  use types.{" + ", ".join(kebab(name) for name in names) + "};\n"
            for name, args, result in functions:
                wit += "  " + identifier(name) + ": func(args: " + kebab(args) + ") -> result<" + (kebab(result) if result else "_") + ", " + kebab(error) + ">;\n"
            wit += "}\n\n"
        wit += "world vendor-adapter {\n" + "".join("  import " + name + ";\n" for name in interfaces)
        wit += "  use types.{invocation, response};\n  export invoke: func(request: invocation) -> response;\n}\n"
        rust = header + "use serde::{Serialize, de::DeserializeOwned};\nuse serde_json::{Value, json};\nuse bgx_adapter_v2_sdk::*;\n\n"
        rust += "pub type HostError = " + error + ";\npub type PortResult<T> = Result<T, HostError>;\n"
        rust += "pub const HOST_METHODS: &[&str] = &[" + ", ".join(json.dumps(m[0]) for m in native) + "];\n"
        rust += '''
fn invalid_wire() -> HostError {
    serde_json::from_value(json!({"code":"INVALID_INPUT","message":"Port wire value does not match the public contract"})).expect("generated error shape")
}

pub fn invoke_port<H: HostPorts + ?Sized, A: Serialize, R: DeserializeOwned>(host: &mut H, method: &str, args: &A) -> PortResult<R> {
    let call = serde_json::from_value(json!({"method":method,"args":args})).map_err(|_|invalid_wire())?;
    let result = host.call(call)?;
    serde_json::from_value(result).map_err(|_|invalid_wire())
}

pub trait HostPorts {
    fn call(&mut self, call: HostPortCallV2) -> PortResult<Value>;
'''
        for method, args, result in native:
            name = method.replace(".", "_").replace("-", "_")
            rust += "    fn " + name + "(&mut self, args: " + args + ") -> PortResult<" + result + "> {\n"
            rust += "        invoke_port(self, " + json.dumps(method) + ", &args)\n    }\n"
        rust += "}\n"
        return {ROOT / "wit/vendor-adapter.wit": wit, ROOT / "crates/ports/src/generated.rs": rust}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = Wit().render()
    assert outputs == Wit().render(), "nondeterministic ABI generation"
    for path, source in outputs.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != source.encode(): raise SystemExit("generated WIT/native port drift: " + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(source.encode())
    print("WIT_PORT_GENERATION=PASS same_source=PASS deterministic=PASS")


if __name__ == "__main__": main()
